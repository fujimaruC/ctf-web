"""Run against the preview build. All artifacts stay inside the workspace."""
import os
from pathlib import Path
from playwright.sync_api import sync_playwright, expect

ROOT = Path(__file__).resolve().parents[1]
ARTIFACTS = ROOT / "artifacts"
ARTIFACTS.mkdir(exist_ok=True)
URL = os.environ.get("FLAGFORGE_TEST_URL", "http://127.0.0.1:5173")

with sync_playwright() as p:
    browser = p.chromium.launch(headless=True, args=["--disable-dev-shm-usage"])
    context = browser.new_context(viewport={"width": 1440, "height": 1000}, reduced_motion="reduce")
    page = context.new_page()
    errors = []
    page.on("pageerror", lambda error: errors.append(str(error)))

    def visit(path):
        page.goto(URL + path)
        page.wait_for_load_state("networkidle")

    def audit(name):
        page.add_script_tag(path=str(ROOT / "node_modules/axe-core/axe.min.js"))
        violations = page.evaluate("async () => (await axe.run(document, {runOnly: {type: 'tag', values: ['wcag2a','wcag2aa','wcag21aa','wcag22aa']}})).violations.map(v => ({id:v.id, impact:v.impact, nodes:v.nodes.map(n=>n.target)}))")
        assert not violations, (name, violations)
        assert page.evaluate("document.documentElement.scrollWidth <= innerWidth + 1"), name + " page overflow"
        page.screenshot(path=str(ARTIFACTS / (name + ".png")), full_page=True, animations="disabled")

    visit("/")
    expect(page.get_by_role("heading", level=1)).to_contain_text("Learn to see")
    audit("landing-desktop")
    page.emulate_media(reduced_motion="no-preference")
    page.wait_for_timeout(150)
    page.emulate_media(reduced_motion="reduce")
    page.wait_for_timeout(50)
    assert page.locator(".experiment [data-trace]").first.evaluate("el => el.style.strokeDashoffset === ''"), "Reduced motion did not revert drawing"
    for width in [320, 390, 768]:
        page.set_viewport_size({"width": width, "height": 844})
        audit("landing-" + str(width))
    page.set_viewport_size({"width": 390, "height": 844})
    page.get_by_label("Theme", exact=True).select_option("dark")
    audit("landing-dark")
    page.get_by_label("Theme", exact=True).select_option("light")
    visit("/challenge.html?id=first-observation")
    expect(page.get_by_role("heading", level=1)).to_have_text("Welcome back.")
    page.get_by_role("button", name="Enter as learner").click()
    expect(page.get_by_role("heading", level=1)).to_have_text("First Observation")
    expect(page.get_by_role("heading", level=1)).to_be_focused()
    audit("challenge-mobile")
    page.get_by_label("Flag", exact=True).fill("wrong")
    page.get_by_role("button", name="Verify flag").click()
    expect(page.get_by_role("alert").filter(has_text="does not match")).to_be_visible()
    expect(page.get_by_label("Flag", exact=True)).to_have_value("wrong")
    page.get_by_label("Flag", exact=True).fill("FLAG{observe}")
    page.get_by_role("button", name="Verify flag").click()
    expect(page.get_by_role("heading", name="Discovery verified.")).to_be_visible()
    audit("solved-mobile")
    visit("/challenges")
    page.get_by_label("Search challenges").fill("nothing matches")
    expect(page.get_by_role("heading", name="No discoveries here yet.")).to_be_visible()
    page.get_by_role("button", name="Clear filters").click()
    expect(page.locator(".challenge-card")).to_have_count(7)
    page.get_by_role("radio", name="Crypto", exact=True).click()
    expect(page.get_by_role("radio", name="Crypto", exact=True)).to_be_checked()
    expect(page.locator(".challenge-card")).to_have_count(2)
    page.reload()
    expect(page.get_by_role("radio", name="Crypto", exact=True)).to_be_checked()
    audit("catalog-mobile")
    for route in ["dashboard", "profile", "leaderboard"]:
        visit("/" + route)
        audit(route + "-mobile")
    visit("/profile")
    page.get_by_label("Display name", exact=True).fill("Alex Updated")
    page.get_by_role("button", name="Save profile").click()
    expect(page.get_by_role("heading", level=1)).to_have_text("Alex Updated")
    visit("/admin/challenges")
    expect(page.get_by_role("heading", name="Instructor access required")).to_be_visible()
    page.set_viewport_size({"width": 1440, "height": 1000})
    page.get_by_role("button", name="Sign out").click()
    visit("/login")
    page.get_by_role("button", name="Enter as instructor").click()
    expect(page.get_by_role("heading", level=1)).to_have_text("The challenge collection.")
    audit("admin-desktop")
    page.get_by_role("link", name="Create challenge", exact=True).click()
    page.get_by_label("Challenge title").fill("A browser test")
    page.get_by_label("Challenge brief").fill("Investigate the browser fixture and find the evidence.")
    page.get_by_label("Author", exact=True).fill("Test instructor")
    page.get_by_label("Private flag").fill("FLAG{observe}")
    page.get_by_label("Publish for learners").check()
    page.get_by_role("button", name="Add free hint").click()
    page.get_by_label("Hint 1", exact=True).fill("Look carefully.")
    audit("editor-desktop")
    page.get_by_role("link", name="Cancel editing").click()
    expect(page.get_by_role("dialog")).to_be_visible()
    page.keyboard.press("Escape")
    expect(page.get_by_role("dialog")).not_to_be_visible()
    page.evaluate("history.back()")
    expect(page.get_by_role("dialog")).to_be_visible()
    page.get_by_role("button", name="Keep current state").click()
    expect(page.get_by_label("Challenge title")).to_have_value("A browser test")
    page.get_by_role("button", name="Save challenge", exact=True).click()
    expect(page.get_by_role("status").filter(has_text="Challenge saved")).to_be_visible()
    expect(page.get_by_role("rowheader", name="A browser test")).to_be_visible()
    page.get_by_role("button", name="Delete A browser test", exact=True).click()
    expect(page.get_by_role("dialog")).to_be_visible()
    page.get_by_role("button", name="Delete challenge", exact=True).click()
    expect(page.get_by_role("rowheader", name="A browser test")).not_to_be_visible()
    for route in ["admin/students", "admin/settings", "contact", "privacy", "terms", "forgot-password"]:
        visit("/" + route)
        audit(route.replace("/", "-") + "-desktop")
    page.set_viewport_size({"width": 390, "height": 844})
    page.get_by_label("Theme", exact=True).select_option("dark")
    for route in ["admin/challenges", "admin/students", "profile", "leaderboard"]:
        visit("/" + route)
        audit(route.replace("/", "-") + "-dark-mobile")
    page.get_by_label("Theme", exact=True).select_option("light")
    visit("/challenges.html?category=Crypto")
    expect(page.get_by_role("radio", name="Crypto", exact=True)).to_be_checked()
    visit("/login.html?tab=register&returnTo=%2Fprofile")
    expect(page).to_have_url(URL + "/register?returnTo=%2Fprofile")
    visit("/challenges/deleted-fixture")
    expect(page.get_by_role("heading", name="This challenge is unavailable.")).to_be_visible()
    visit("/unknown-route")
    expect(page.get_by_role("heading", name="This page is outside the map")).to_be_visible()
    visit("/challenges")
    page.keyboard.press("Tab")
    for _ in range(35):
        page.keyboard.press("Tab")
        assert page.evaluate("() => { const e=document.activeElement; return e===document.body || getComputedStyle(e).outlineStyle!=='none'; }"), "Invisible keyboard focus"
    assert not errors, errors
    context.close()
    browser.close()
    print("Browser flows, responsive layouts, themes, keyboard focus, and axe checks passed.")
